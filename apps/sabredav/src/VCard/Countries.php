    /**
     * Map a country code or an English/German name to its alpha-2 code.
     * Unknown text is returned trimmed and unchanged; empty input returns null.
     */
    public static function toCode(?string $value): ?string
    {
        $trimmed = trim($value ?? '');
        if ($trimmed === '') {
            return null;
        }
        $upper = strtoupper($trimmed);
        if (isset(self::NAMES[$upper])) {
            return $upper;
        }
        return self::LOOKUP[mb_strtolower($trimmed)] ?? $trimmed;
    }

    /**
     * English official name for a stored code; legacy free text unchanged.
     */
    public static function toName(?string $value): string
    {
        if ($value === null) {
            return '';
        }
        return self::NAMES[$value] ?? $value;
    }
